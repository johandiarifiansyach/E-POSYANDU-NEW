import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const workerRoot = resolve(import.meta.dirname, '..');
const repositoryRoot = resolve(workerRoot, '..');
const standards = JSON.parse(readFileSync(resolve(workerRoot, 'data/anthropometry.json'), 'utf8'));

const metricNames = {
  weightForAge: 'weight_for_age',
  lengthHeightForAge: 'length_height_for_age',
  bmiForAge: 'bmi_for_age',
  weightForLength: 'weight_for_length',
  weightForHeight: 'weight_for_height'
};

const rows = Object.entries(metricNames).flatMap(([source, metric]) =>
  Object.entries(standards[source]).map(([sex, values]) =>
    `  ('${metric}', '${sex}', $json$${JSON.stringify(values)}$json$::jsonb)`
  )
);

const sql = `-- Generated by backend/scripts/generate-cloudflare-sql.mjs.
-- Run this once in Supabase SQL Editor before activating the Cloudflare Worker.
begin;

create table if not exists public.eposyandu_growth_lms (
  metric text not null,
  sex char(1) not null check (sex in ('L', 'P')),
  values_json jsonb not null,
  primary key (metric, sex)
);

insert into public.eposyandu_growth_lms (metric, sex, values_json)
values
${rows.join(',\n')}
on conflict (metric, sex) do update set values_json = excluded.values_json;

create or replace function public.eposyandu_lms(
  p_metric text,
  p_sex char(1),
  p_index integer
) returns double precision[]
language sql
stable
set search_path = public
as $$
  select array[
    (values_json -> p_index ->> 0)::double precision,
    (values_json -> p_index ->> 1)::double precision,
    (values_json -> p_index ->> 2)::double precision
  ]
  from public.eposyandu_growth_lms
  where metric = p_metric
    and sex = p_sex
    and p_index between 0 and jsonb_array_length(values_json) - 1
$$;

create or replace function public.eposyandu_zscore(
  p_value double precision,
  p_lms double precision[]
) returns double precision
language sql
immutable
as $$
  select case
    when p_lms is null or array_length(p_lms, 1) <> 3 then null
    when p_lms[1] = 0 then ln(p_value / p_lms[2]) / p_lms[3]
    else (power(p_value / p_lms[2], p_lms[1]) - 1) / (p_lms[1] * p_lms[3])
  end
$$;

create or replace function public.eposyandu_adjusted_height(
  p_value double precision,
  p_age_months integer,
  p_method text
) returns double precision
language sql
immutable
as $$
  select case
    when p_age_months <= 24 and p_method = 'Berdiri' then p_value + 0.7
    when p_age_months > 24 and p_method = 'Terlentang' then p_value - 0.7
    else p_value
  end
$$;

create or replace function public.eposyandu_growth_status(
  p_value double precision,
  p_metric text,
  p_age_months integer,
  p_sex char(1),
  p_secondary double precision default null,
  p_method text default ''
) returns text
language plpgsql
stable
set search_path = public
as $$
declare
  v_lms double precision[];
  v_score double precision;
  v_height double precision;
  v_index integer;
begin
  if p_value is null or p_value <= 0 or p_age_months not between 0 and 60 or p_sex not in ('L', 'P') then
    return '-';
  end if;

  if p_metric = 'BBU' then
    v_lms := public.eposyandu_lms('weight_for_age', p_sex, p_age_months);
  elsif p_metric = 'TBU' then
    v_lms := public.eposyandu_lms('length_height_for_age', p_sex, p_age_months);
    p_value := public.eposyandu_adjusted_height(p_value, p_age_months, coalesce(p_method, ''));
  elsif p_metric = 'IMTU' then
    if p_secondary is null or p_secondary <= 0 then return '-'; end if;
    v_height := public.eposyandu_adjusted_height(p_secondary, p_age_months, coalesce(p_method, ''));
    v_lms := public.eposyandu_lms('bmi_for_age', p_sex, p_age_months);
    p_value := p_value / power(v_height / 100, 2);
  elsif p_metric = 'BBTB' then
    if p_secondary is null or p_secondary <= 0 then return '-'; end if;
    v_height := public.eposyandu_adjusted_height(p_secondary, p_age_months, coalesce(p_method, ''));
    if p_age_months <= 24 then
      v_index := round((v_height - 45) * 2)::integer;
      v_lms := public.eposyandu_lms('weight_for_length', p_sex, v_index);
    else
      v_index := round((v_height - 65) * 2)::integer;
      v_lms := public.eposyandu_lms('weight_for_height', p_sex, v_index);
    end if;
  else
    return '-';
  end if;

  v_score := public.eposyandu_zscore(p_value, v_lms);
  if v_score is null then return '-'; end if;

  if p_metric = 'BBU' then
    if v_score < -3 then return 'Berat Sangat Kurang'; end if;
    if v_score < -2 then return 'Berat Kurang'; end if;
    if v_score <= 1 then return 'Berat Normal'; end if;
    return 'Risiko Berat Lebih';
  elsif p_metric = 'TBU' then
    if v_score < -3 then return 'Sangat Pendek'; end if;
    if v_score < -2 then return 'Pendek'; end if;
    if v_score <= 3 then return 'Normal'; end if;
    return 'Tinggi';
  end if;

  if v_score < -3 then return 'Gizi Buruk'; end if;
  if v_score < -2 then return 'Gizi Kurang'; end if;
  if v_score <= 1 then return 'Gizi Baik'; end if;
  if v_score <= 2 then return 'Risiko Gizi Lebih'; end if;
  if v_score <= 3 then return 'Gizi Lebih'; end if;
  return 'Obesitas';
end;
$$;

create or replace function public.eposyandu_age_months(
  p_birth_date date,
  p_reference_date date
) returns integer
language sql
immutable
as $$
  select greatest(0, (extract(year from age(p_reference_date, p_birth_date)) * 12 + extract(month from age(p_reference_date, p_birth_date)))::integer)
$$;

create or replace function public.eposyandu_scope_match(
  p_village text,
  p_posyandu text,
  p_requested_village text,
  p_requested_posyandu text,
  p_role text,
  p_scope_village text,
  p_scope_posyandu text
) returns boolean
language sql
immutable
as $$
  select (p_requested_village is null or p_village = p_requested_village)
    and (p_requested_posyandu is null or p_posyandu = p_requested_posyandu)
    and (p_role = 'Ahli Gizi' or p_village = p_scope_village)
    and (p_role <> 'Kader Posyandu' or p_posyandu = p_scope_posyandu)
$$;

create or replace function public.eposyandu_exclusive_breastfeeding_page(
  p_measurement_start date,
  p_measurement_end date,
  p_age_group text,
  p_page integer,
  p_size integer,
  p_village text default null,
  p_posyandu text default null,
  p_role text default 'Ahli Gizi',
  p_scope_village text default null,
  p_scope_posyandu text default null
) returns jsonb
language sql
stable
set search_path = public
as $$
  with latest_measurements as (
    select distinct on (m.legacy_child_id)
      m.legacy_child_id, m.measurement_date, m.exclusive_breastfeeding, m.created_at
    from public.measurements m
    where m.measurement_date between p_measurement_start and p_measurement_end
    order by m.legacy_child_id, m.measurement_date desc, m.created_at desc
  ), filtered as (
    select c.id, c.name, c.national_id, c.has_national_id, c.birth_date, c.village, c.posyandu,
      l.measurement_date,
      public.eposyandu_age_months(c.birth_date, l.measurement_date) as age_in_months
    from public.children c
    join latest_measurements l on l.legacy_child_id = c.id
    where c.deleted_at is null
      and l.exclusive_breastfeeding = 'Ya'
      and public.eposyandu_scope_match(c.village, c.posyandu, p_village, p_posyandu, p_role, p_scope_village, p_scope_posyandu)
  ), scoped as (
    select * from filtered
    where (p_age_group = '0-5' and age_in_months between 0 and 5)
       or (p_age_group = '6' and age_in_months = 6)
  ), paged as (
    select * from scoped
    order by lower(name), id
    limit greatest(1, least(p_size, 50))
    offset greatest(0, p_page - 1) * greatest(1, least(p_size, 50))
  )
  select jsonb_build_object(
    'items', coalesce((select jsonb_agg(jsonb_build_object(
      'id', id,
      'data', jsonb_build_object(
        'nama', name, 'nik', national_id, 'hasNIK', has_national_id, 'tglLahir', birth_date,
        'desa', village, 'posyandu', posyandu, 'tglUkur', measurement_date, 'ageInMonths', age_in_months
      )
    )) from paged), '[]'::jsonb),
    'total', (select count(*) from scoped)
  )
$$;

create or replace function public.eposyandu_dashboard_stats(
  p_month_start date,
  p_month_end date,
  p_previous_month_start date,
  p_previous_month_end date,
  p_village text default null,
  p_posyandu text default null,
  p_role text default 'Ahli Gizi',
  p_scope_village text default null,
  p_scope_posyandu text default null
) returns jsonb
language sql
stable
set search_path = public
as $$
  with active_children as (
    select c.id, c.birth_date, c.sex,
      ((c.created_at at time zone 'Asia/Jakarta') >= p_month_start and (c.created_at at time zone 'Asia/Jakarta') < (p_month_start + interval '1 month')) as created_in_month,
      exists (
        select 1 from public.measurements previous_measurement
        where previous_measurement.child_id = c.id
          and previous_measurement.measurement_date between p_previous_month_start and p_previous_month_end
      ) as measured_previous_month
    from public.children c
    where c.deleted_at is null
      and c.birth_date <= p_month_start
      and c.birth_date > (p_month_start - interval '60 months')::date
      and public.eposyandu_scope_match(c.village, c.posyandu, p_village, p_posyandu, p_role, p_scope_village, p_scope_posyandu)
  ), latest_current_measurements as (
    select distinct on (m.child_id)
      m.child_id, m.measurement_date, m.weight_kg::double precision as weight_kg,
      m.height_cm::double precision as height_cm, m.measurement_method, m.weight_gain_status,
      m.exclusive_breastfeeding
    from public.measurements m
    join active_children c on c.id = m.child_id
    where m.measurement_date between p_month_start and p_month_end
    order by m.child_id, m.measurement_date desc, m.created_at desc
  ), calculated as (
    select c.*, m.measurement_date, m.weight_kg, m.height_cm, m.measurement_method,
      m.weight_gain_status, m.exclusive_breastfeeding,
      public.eposyandu_age_months(c.birth_date, coalesce(m.measurement_date, p_month_end)) as age_in_months,
      public.eposyandu_growth_status(m.weight_kg, 'BBU', public.eposyandu_age_months(c.birth_date, coalesce(m.measurement_date, p_month_end)), c.sex, null, m.measurement_method) as bbu_status,
      public.eposyandu_growth_status(m.height_cm, 'TBU', public.eposyandu_age_months(c.birth_date, coalesce(m.measurement_date, p_month_end)), c.sex, null, m.measurement_method) as tbu_status,
      public.eposyandu_growth_status(m.weight_kg, 'BBTB', public.eposyandu_age_months(c.birth_date, coalesce(m.measurement_date, p_month_end)), c.sex, m.height_cm, m.measurement_method) as bbtb_status
    from active_children c
    left join latest_current_measurements m on m.child_id = c.id
  ), counts as (
    select
      count(*)::integer as s,
      count(*) filter (where weight_kg > 0)::integer as d,
      count(*) filter (where weight_kg > 0 and weight_gain_status = 'N')::integer as n,
      count(*) filter (where weight_kg > 0 and weight_gain_status = 'T')::integer as t,
      count(*) filter (where created_in_month)::integer as b,
      count(*) filter (where not measured_previous_month)::integer as o,
      count(*) filter (where age_in_months = 6 and exclusive_breastfeeding = 'Ya')::integer as asi_eksklusif,
      count(*) filter (where age_in_months = 6)::integer as asi_target,
      count(*) filter (where weight_kg > 0 and bbu_status in ('Berat Sangat Kurang', 'Berat Kurang'))::integer as underweight,
      count(*) filter (where weight_kg > 0 and tbu_status in ('Sangat Pendek', 'Pendek'))::integer as stunting,
      count(*) filter (where weight_kg > 0 and bbtb_status in ('Gizi Buruk', 'Gizi Kurang'))::integer as wasting
    from calculated
  )
  select jsonb_build_object(
    'S', s, 'D', d, 'N', n, 'T', t, 'B', b, 'O', o,
    'asiEksklusif', asi_eksklusif, 'asiTarget', asi_target,
    'underweight', underweight, 'stunting', stunting, 'wasting', wasting,
    'perD', case when s = 0 then '0' else round(d::numeric * 100 / s, 1)::text end,
    'perN', case when d = 0 then '0' else round(n::numeric * 100 / d, 1)::text end,
    'perT', case when d = 0 then '0' else round(t::numeric * 100 / d, 1)::text end,
    'perAsiEksklusif', case when asi_target = 0 then '0' else round(asi_eksklusif::numeric * 100 / asi_target, 1)::text end,
    'perUnderweight', case when d = 0 then '0' else round(underweight::numeric * 100 / d, 1)::text end,
    'perStunting', case when d = 0 then '0' else round(stunting::numeric * 100 / d, 1)::text end,
    'perWasting', case when d = 0 then '0' else round(wasting::numeric * 100 / d, 1)::text end
  ) from counts
$$;

revoke all on function public.eposyandu_exclusive_breastfeeding_page(date, date, text, integer, integer, text, text, text, text, text) from public;
revoke all on function public.eposyandu_dashboard_stats(date, date, date, date, text, text, text, text, text) from public;

commit;
`;

